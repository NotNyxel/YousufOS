#!/usr/bin/env python3
"""Regenerates src/data/quran.js (Ayah of the day) from api.alquran.cloud.
Edit REFS to change which verses appear. Run from the project root:
    python3 scripts/fetch-quran.py
"""
import json, time, urllib.request

REFS = ("1:5 2:45 2:152 2:153 2:186 2:201 2:286 3:8 3:139 3:173 3:200 6:162 7:56 8:46 9:51 11:115 "
        "13:28 14:7 16:97 16:128 18:46 20:114 21:87 25:63 29:69 33:41 33:56 39:10 39:53 40:60 41:34 "
        "49:10 49:13 51:56 55:13 64:16 65:3 67:2 93:5 94:5 94:6 103:2 103:3 112:1 2:110 3:191 17:80 "
        "20:25 28:24 35:2 50:16 57:20 2:214 73:20").split()
MAX_AYAH, MAX_TAFSIR = 300, 520  # keep the TV card readable

out = []
for ref in REFS:
    url = f"https://api.alquran.cloud/v1/ayah/{ref}/editions/quran-uthmani,en.sahih,ar.muyassar"
    for _ in range(3):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "YousufOS/1.0"})
            data = json.load(urllib.request.urlopen(req, timeout=20))["data"]
            break
        except Exception:
            time.sleep(2)
    else:
        print("failed", ref)
        continue
    ar, en, tafsir = data
    if len(ar["text"]) > MAX_AYAH or len(tafsir["text"]) > MAX_TAFSIR:
        print("skipping long", ref)
        continue
    out.append(dict(ref=ref, surah=ar["surah"]["englishName"], surahAr=ar["surah"]["name"].replace("سُورَةُ ", "").strip(),
                    ayah=ar["numberInSurah"], ar=ar["text"], en=en["text"], tafsir=tafsir["text"]))

js = ("// Qur'an ayat for the Home screen card (one per day).\n"
      "// Text: Uthmani script (Tanzil, via api.alquran.cloud). Translation: Sahih International.\n"
      "// Explanation: Tafsir al-Muyassar (King Fahd Complex). Generated by scripts/fetch-quran.py.\n"
      "export const AYAT = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n\n"
      "export function ayahOfTheDay(date = new Date()) {\n"
      "  const start = new Date(date.getFullYear(), 0, 0);\n"
      "  const day = Math.floor((date - start) / 86400000);\n"
      "  return AYAT[(day * 7 + date.getFullYear()) % AYAT.length];\n}\n")
open("src/data/quran.js", "w", encoding="utf-8").write(js)
print(len(out), "ayat written")
